export const translations: Record<Lang, Record<keyof typeof en, string>> = { 'en-US': en, 'pt-BR': pt }

const interpolate = (template: string, vars?: TVars) =>
  vars ? template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match)) : template

export const translate = (lang: Lang, key: TKey, vars?: TVars) => {
  const dict = translations[lang]
  const count = vars && typeof vars.count === 'number' ? vars.count : vars && typeof vars.n === 'number' ? vars.n : undefined
  const oneKey = `${key}_one` as keyof typeof en
  const template = count === 1 && oneKey in dict ? dict[oneKey] : dict[key]
  return interpolate(template, vars)
}
